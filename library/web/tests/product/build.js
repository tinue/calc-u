#!/usr/bin/env node
//
// Puts one dist/ of the test product together on
// the build both products' build.js call (library/web/build/dist.js
// buildProduct):
//
//   node build.js --name Test-A --version 1.0.0 --wasm <dir> --out <dist>
//
// <dir> holds calcutest-core.js and .wasm (build/web/library/web/). The
// product's name gives its component's text, its store (mount
// /persist-<name>) and its lock; the version goes into calc.js and into
// bundle/version.txt, which the worker loads (all files of one
// release). React and Babel are the library's one vendored copy
// (library/web/vendor/, dist.VENDOR), which both products use.

const fs = require("fs");
const path = require("path");
const dist = require("../../build/dist.js");

const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, "")] = process.argv[i + 1];
for (const k of ["name", "version", "wasm", "out"])
  if (!args[k]) throw new Error(`build.js: --${k} is missing`);

const HERE = __dirname;
const VENDOR = dist.VENDOR;
const OUT = path.resolve(args.out);
const NAME = args.name;
const ID = NAME.toLowerCase().replace(/[^a-z0-9]+/g, "-");
const ICON = Buffer.from(
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==", "base64");

fs.rmSync(OUT, { recursive: true, force: true });
for (const d of ["wasm", "bundle", "presets/demo", "app", "vendor", "img", "tests"]) fs.mkdirSync(path.join(OUT, d), { recursive: true });
const write = (rel, text) => fs.writeFileSync(path.join(OUT, rel), text);
const copy = (from, rel) => fs.copyFileSync(from, path.join(OUT, rel));

// The engine and the product's files.
copy(path.join(args.wasm, "calcutest-core.js"), "wasm/calcutest-core.js");
copy(path.join(args.wasm, "calcutest-core.wasm"), "wasm/calcutest-core.wasm");
write("bundle/version.txt", args.version);
write("bundle/demo.txt", "a bundled file\n");
write("presets/dot.test", "model: test-dot\n");
write("presets/demo/seg.test", "model: test-seg\n");
fs.writeFileSync(path.join(OUT, "img", "icon.png"), ICON);
copy(path.join(HERE, "index.html"), "index.html");
for (const f of ["react.production.min.js", "react-dom.production.min.js"]) copy(path.join(VENDOR, f), `vendor/${f}`);
dist.writeProductWorker(OUT, {
  name: NAME, wasm: "calcutest-core", factory: "createCalcUTestModule", host: "CalcUTestHost",
  mount: `/persist-${ID}`, lock: `${ID}-storage`,
});

// Workers for the failure tests (a start that fails, an unreadable store,
// no store): beside the product's,
// in tests/, started through the workerUrl prop.
write("tests/broken-worker.js", 'throw new Error("broken on purpose");\n');
write("tests/unreadable-worker.js",
  "// IndexedDB opens, but reading the store fails.\n" +
  'IDBIndex.prototype.openKeyCursor = function () { throw new DOMException("stubbed read", "UnknownError"); };\n' +
  'self.CALC_ROOT = "../";\nimportScripts("../calc-engine-worker.js");\n');
write("tests/unavailable-worker.js",
  "// IndexedDB cannot be opened (private mode, a full store).\n" +
  'IDBFactory.prototype.open = function () { throw new DOMException("stubbed open", "InvalidStateError"); };\n' +
  'self.CALC_ROOT = "../";\nimportScripts("../calc-engine-worker.js");\n');

copy(path.join(HERE, "app.css"), "app/app.css");
fs.writeFileSync(path.join(OUT, "app", "icon.png"), ICON);
write("app/manifest.json", JSON.stringify({
  name: NAME, short_name: NAME, start_url: "./", scope: "./", display: "standalone",
  background_color: "#ffffff", theme_color: "#ffffff",
  icons: [{ src: "icon.png", sizes: "1x1", type: "image/png" }],
}, null, 2) + "\n");
write("app/index.html", `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${NAME}</title>
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<link rel="manifest" href="manifest.json">
<link rel="icon" type="image/png" href="icon.png">
<link rel="stylesheet" href="../calc.css">
<link rel="stylesheet" href="app.css">
</head>
<body>
<div id="root"></div>
<script src="../vendor/react.production.min.js"></script>
<script src="../vendor/react-dom.production.min.js"></script>
<script src="../calc.js"></script>
<script src="app.js"></script>
</body>
</html>
`);

// The library's parts, the product's styles with the component set's (the
// paper panel), calc.js and app/app.js.
dist.buildProduct({
  dist: OUT,
  name: `${NAME}-web`,
  version: args.version,
  css: path.join(HERE, "calc.css"),
  sources: [path.join(HERE, "src", "CalcUTest.jsx")],
  replace: { __CALCU_PRODUCT__: NAME },
  banner: `${NAME} (the Web shell's test product) -- generated by library/web/tests/product/build.js.`,
  component: "CalcUTest", props: {},
  installSentence: `Install ${NAME} to run it offline in its own window.`,
  swId: ID,
  core: ["vendor/react.production.min.js", "vendor/react-dom.production.min.js", "img/icon.png",
    "wasm/calcutest-core.js", "wasm/calcutest-core.wasm"],
});
