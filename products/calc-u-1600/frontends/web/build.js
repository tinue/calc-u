#!/usr/bin/env node
//
// The JavaScript half of frontends/web/build.sh, run after the engine and the
// static files are in dist/: the library's product build
// (library/web/build/dist.js buildProduct; LIB-15 design §3.5) with the
// product's data: calc.js from src/*.jsx, app/app.js with CalcU1600, the
// presets of examples/bundle.yaml (C1600-4 AC-17, LIB-6 AC-31), the service
// worker's precached core and MANIFEST.json. The version is release.yaml's
// (the Qt app's APP_VERSION).

const path = require("path");

const WEB = __dirname;
const REPO = path.join(WEB, "..", "..");   // the product directory
const ROOT = path.join(REPO, "..", "..");  // the repository
const DIST = process.env.CALCU1600_WEB_DIST || path.join(WEB, "dist");
const dist = require(path.join(ROOT, "library", "web", "build", "dist.js"));

dist.buildProduct({
  dist: DIST,
  name: "Calc-U-1600-web",
  version: dist.releaseVersion(REPO),
  css: path.join(WEB, "calc.css"),
  // In load order; one closure, so nothing but CalcU1600 reaches the page.
  sources: ["painters.js", "Faceplate.jsx", "Panels.jsx", "Dialogs.jsx", "CalcU1600.jsx"].map((n) => path.join(WEB, "src", n)),
  banner: "Calc-U-1600 web client -- generated by frontends/web/build.sh from frontends/web/src/ and library/web/src/.",
  component: "CalcU1600", props: { layout: "auto" },
  installSentence: "Install Calc-U-1600 to run it offline in its own window.",
  bundle: path.join(REPO, "examples", "bundle.yaml"),
  swId: "calc-u-1600",
  core: ["vendor/react.production.min.js", "vendor/react-dom.production.min.js",
    "img/pc1500.png", "img/pc1500A.png", "img/pc1600.png", "img/icon.png",
    "wasm/calcu1600-core.js", "wasm/calcu1600-core.wasm"],
});
