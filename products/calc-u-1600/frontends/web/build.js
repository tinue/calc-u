#!/usr/bin/env node
//
// The JavaScript half of frontends/web/build.sh, run after the engine and the
// static files are in dist/, on the library's build steps
// (library/web/build/dist.js; LIB-15 design §3.5):
//
//   1. calc.js: the library's page side and src/*.jsx in one closure
//      (AC-15); app/app.js from the library's app page with CalcU1600.
//   2. The library's worker, service worker template, app worker entry and
//      audio worklet.
//   3. examples/bundled.yaml and the presets it lists -- each with the other
//      files of its examples/ folder, which a preset names by relative path
//      -- into dist/presets/ (the engine's bundled examples).
//   4. dist/files.json, the service worker's precache list and stamp, and
//      dist/MANIFEST.json (the library's).

const fs = require("fs");
const path = require("path");

const WEB = __dirname;
const REPO = path.join(WEB, "..", "..");   // the product directory
const ROOT = path.join(REPO, "..", "..");  // the repository
const DIST = process.env.CALCU1600_WEB_DIST || path.join(WEB, "dist");
const VENDOR = path.join(WEB, "vendor");
const dist = require(path.join(ROOT, "library", "web", "build", "dist.js"));

const read = (p) => fs.readFileSync(p, "utf8");

// The one version: the Qt app's APP_VERSION.
const version = read(path.join(REPO, "frontends", "qt6", "CMakeLists.txt")).match(/set\(APP_VERSION "([0-9.]+)"\)/)[1];

// ---- 1. Compile ---------------------------------------------------------

const css = read(path.join(WEB, "calc.css"));
const outside = dist.checkScopedCss(css);
if (outside.length) console.warn(`calc.css: selectors outside .calcu-client (LIB-15 AC-17): ${outside.join(", ")}`);

// In load order; one closure, so nothing but CalcU1600 reaches the page.
const SOURCES = ["engine.js", "painters.js", "Faceplate.jsx", "MenuBar.jsx", "ControlBar.jsx", "Panels.jsx", "Dialogs.jsx",
  "CalcU1600.jsx"].map((n) => path.join(WEB, "src", n));
dist.compileCalcJs({
  vendor: VENDOR,
  productSources: SOURCES,
  replace: { __CALC_VERSION__: version },
  banner: "Calc-U-1600 web client -- generated by frontends/web/build.sh from frontends/web/src/ and library/web/src/.",
  out: path.join(DIST, "calc.js"),
});
dist.compileApp({
  vendor: VENDOR, component: "CalcU1600", props: {},
  installSentence: "Install Calc-U-1600 to run it offline in its own window.",
  out: path.join(DIST, "app", "app.js"),
});
console.log("compiled calc.js, app/app.js");

// ---- 2. The library's files ---------------------------------------------

dist.copyAppFiles(DIST);
dist.writeLibraryWorker(DIST);

// ---- 3. Presets ---------------------------------------------------------

// Only the `file:` lines of both lists are needed here.
const bundledList = path.join(REPO, "examples", "bundled.yaml");
const presets = read(bundledList).split("\n")
  .map((line) => line.match(/^\s*(?:- )?file:\s*(\S.*?)\s*$/))
  .filter(Boolean).map((m) => m[1]);
const presetDirs = [...new Set(presets.map((f) => path.dirname(f)))];
for (const dir of presetDirs) {
  const from = path.join(REPO, "examples", dir);
  for (const f of fs.readdirSync(from, { withFileTypes: true })) {
    if (!f.isFile() || f.name.startsWith(".")) continue;
    fs.mkdirSync(path.join(DIST, "presets", dir), { recursive: true });
    fs.copyFileSync(path.join(from, f.name), path.join(DIST, "presets", dir, f.name));
  }
}
for (const f of presets)
  if (!fs.existsSync(path.join(DIST, "presets", f))) throw new Error(`bundled.yaml: ${f} is not in examples/`);
fs.copyFileSync(bundledList, path.join(DIST, "presets", "bundled.yaml"));
console.log(`presets: ${presets.length} from ${presetDirs.join(", ")}`);

// ---- 4. files.json, service worker, MANIFEST.json ------------------------

dist.writeFilesList(DIST);
const precached = dist.stampServiceWorker(DIST, {
  id: "calc-u-1600",
  core: ["vendor/react.production.min.js", "vendor/react-dom.production.min.js",
    "img/pc1500.png", "img/pc1500A.png", "img/pc1600.png", "img/icon.png",
    "wasm/calcu1600-core.js", "wasm/calcu1600-core.wasm"],
});
console.log(`app/sw.js: ${precached.length} precached files`);
const manifest = dist.writeManifest(DIST, { name: "Calc-U-1600-web", version });
console.log(`MANIFEST.json: ${version}, ${manifest.commit}, ${Object.keys(manifest.files).length} files`);
