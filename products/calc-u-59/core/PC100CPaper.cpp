double inkAlpha(int heat) {
    if (heat >= kFullInkCycles) return 1.0;
    return 0.05 + 0.95 * std::pow(heat < 0 ? 0.0 : heat / double(kFullInkCycles), 2.5);
}

const calcu::paper::PaperDescription& description() {
    static const calcu::paper::PaperDescription d = [] {
        calcu::paper::PaperDescription p;
        p.unit = calcu::paper::Millimetres{430, 1000};
        p.width = kPaperWidth;
        p.printableLeft = kMargin;
        p.printableWidth = kWidth;
        p.form = calcu::paper::MarkForm::Dots;
        p.dotDiameter = 7'600;   // 0.38 of the pitch as radius
        for (int heat = 0; heat <= kFullInkCycles; ++heat)
            p.darknessGreys.push_back(static_cast<std::uint8_t>(std::lround(255.0 * (1.0 - inkAlpha(heat)))));
        p.pictureDotsPerInch = 600;
        p.textLayer = true;
        return p;
    }();
    return d;
}

std::vector<Dot> lineDots(const std::array<std::uint8_t, 20>& codes, int rowCount, int partialColumns, int partialHeat,
                          Coord top) {
    std::vector<Dot> out;
    const int heat = partialHeat < kFullInkCycles ? partialHeat : kFullInkCycles;
    for (std::size_t i = 0; i < codes.size(); ++i) {
        const std::uint8_t* glyph = kFont[codes[i] & 0x3F];
        for (int r = 0; r < 7; ++r) {
            const auto inked = static_cast<std::uint8_t>(inkedColumns(rowCount, partialColumns, r) & glyph[r]);
            const std::uint8_t faint = faintColumns(rowCount, partialColumns, partialHeat, r);
            for (int c = 0; c < 5; ++c) {
                const auto bit = static_cast<std::uint8_t>(0x10 >> c);
                if (!(inked & bit)) continue;
                const auto darkness = static_cast<std::uint8_t>((faint & bit) ? heat : kFullInkCycles);
                out.push_back(Dot{Position{kMargin + static_cast<Coord>(i) * kCharStep + c * kPerUnit + kPerUnit / 2,
                                           top + r * kPerUnit + kPerUnit / 2},
                                  darkness});
            }
        }
    }
    return out;
}

