#!/usr/bin/env node
//
// The JavaScript half of frontends/web/build.sh, run after the engine and the
// static files are in dist/: the library's product build
// (library/web/build/dist.js buildProduct; LIB-15 design §3.5) with the
// product's data: calc.js from src/*.jsx, app/app.js with CalcU59,
// examples/bundle.yaml and exactly the files it lists (C59-2 AC-13, AC-14,
// LIB-6 AC-31; preloaded at /presets), the service worker's precached core
// and MANIFEST.json. The version is release.yaml's (the Xcode project's
// MARKETING_VERSION, also stamped into calc.js for the Settings dialog).
//
// reference/WebClient.md is the contract for what dist/ contains.

const fs = require("fs");
const path = require("path");

const WEB = __dirname;
const REPO = path.join(WEB, "..", "..");  // the product directory
const ROOT = path.join(REPO, "..", "..");  // the repository
// CALCU59_WEB_DIST: another output folder (build.sh, tests/rom_missing_build.sh).
const DIST = process.env.CALCU59_WEB_DIST || path.join(WEB, "dist");
const dist = require(path.join(ROOT, "library", "web", "build", "dist.js"));

// What build.sh copied into a folder of dist/.
const filesOf = (dir) => fs.readdirSync(path.join(DIST, dir)).filter((f) => !f.startsWith(".")).map((f) => `${dir}/${f}`);

dist.buildProduct({
  dist: DIST,
  name: "Calc-U-59-web",
  version: dist.releaseVersion(REPO),
  css: path.join(WEB, "calc.css"),
  // In load order: helpers before the components that use them. One closure,
  // so nothing but CalcU59 reaches the host page's globals.
  sources: ["page.jsx", "painters.js", "CalculatorFace.jsx", "Dialogs.jsx", "Paper.jsx", "Debugger.jsx",
    "CalcU59.jsx"].map((n) => path.join(WEB, "src", n)),
  banner: "Calc-U 59 web client -- generated by frontends/web/build.sh from frontends/web/src/ and library/web/src/.",
  component: "CalcU59", props: { layout: "auto" },
  installSentence: "Install Calc-U 59 for one-tap, full-screen launches.",
  bundle: path.join(REPO, "examples", "bundle.yaml"),
  swId: "calcu59",   // 2.3.0's cache names: its caches go at the first activation
  core: ["vendor/react.production.min.js", "vendor/react-dom.production.min.js", "wasm/ti59-core.js", "wasm/ti59-core.wasm",
    ...filesOf("fonts"), ...filesOf("img")],
});
