#!/usr/bin/env node
//
// The JavaScript half of frontends/web/build.sh, run after the engine and the
// static files are in dist/, on the library's build steps
// (library/web/build/dist.js; LIB-15 design §3.5):
//
//   1. calc.js: the library's page side and src/*.jsx in one closure
//      (AC-15); app/app.js from the library's app page with PlayCalculator.
//   2. The library's worker, service worker template and app worker entry.
//   3. The presets PlayCalculator offers (presets.json) from examples/ into
//      dist/presets/, with their manifest (the Preset dialog's list; the
//      engine finds a `preset` prop's file there).
//   4. dist/files.json, the service worker's precache list and stamp, and
//      dist/MANIFEST.json (the library's).
//
// reference/WebClient.md is the contract for what dist/ contains.

const fs = require("fs");
const path = require("path");

const WEB = __dirname;
const REPO = path.join(WEB, "..", "..");  // the product directory
const ROOT = path.join(REPO, "..", "..");  // the repository
// CALCU59_WEB_DIST: another output folder (build.sh, tests/rom_missing_build.sh).
const DIST = process.env.CALCU59_WEB_DIST || path.join(WEB, "dist");
const VENDOR = path.join(WEB, "vendor");
const dist = require(path.join(ROOT, "library", "web", "build", "dist.js"));

const read = (p) => fs.readFileSync(p, "utf8");

// The one version: the Xcode project's MARKETING_VERSION, as the Qt build
// reads it (also stamped into calc.js for the Settings dialog).
const version = read(path.join(REPO, "frontends", "swift", "Calc-U-59.xcodeproj", "project.pbxproj"))
  .match(/MARKETING_VERSION = ([0-9]+\.[0-9.]+);/)[1];

// ---- 1. Compile ---------------------------------------------------------

const css = read(path.join(WEB, "calc.css"));
const outside = dist.checkScopedCss(css);
if (outside.length) throw new Error(`calc.css: selectors outside .calcu-client (LIB-15 AC-17): ${outside.join(", ")}`);

// In load order: helpers before the components that use them. One closure,
// so nothing but PlayCalculator reaches the host page's globals.
const SOURCES = ["engine.js", "painters.js", "CalculatorFace.jsx", "ControlBar.jsx", "Dialogs.jsx",
  "Printer.jsx", "Debugger.jsx", "PlayCalculator.jsx"].map((n) => path.join(WEB, "src", n));
dist.compileCalcJs({
  vendor: VENDOR,
  productSources: SOURCES,
  replace: { __CALC_VERSION__: version },
  banner: "Calc-U 59 web client -- generated by frontends/web/build.sh from frontends/web/src/ and library/web/src/.",
  out: path.join(DIST, "calc.js"),
});
dist.compileApp({
  vendor: VENDOR, component: "PlayCalculator", props: { layout: "auto" },
  installSentence: "Install Calc-U 59 for one-tap, full-screen launches.",
  out: path.join(DIST, "app", "app.js"),
});
console.log("compiled calc.js, app/app.js");

// ---- 2. The library's files ---------------------------------------------

dist.copyAppFiles(DIST);
dist.writeLibraryWorker(DIST);

// ---- 3. Presets ---------------------------------------------------------

fs.mkdirSync(path.join(DIST, "presets"), { recursive: true });
const presets = JSON.parse(read(path.join(WEB, "presets.json")));
for (const p of presets) fs.copyFileSync(path.join(REPO, "examples", p.file), path.join(DIST, "presets", p.file));
fs.writeFileSync(path.join(DIST, "presets", "manifest.json"), JSON.stringify(presets, null, 2) + "\n");
console.log(`presets: ${presets.map((p) => p.file).join(", ")}`);

// ---- 4. files.json, service worker, MANIFEST.json ------------------------

dist.writeFilesList(DIST);
const fonts = fs.readdirSync(path.join(DIST, "fonts")).filter((f) => !f.startsWith(".")).map((f) => `fonts/${f}`);
const images = fs.readdirSync(path.join(DIST, "img")).filter((f) => !f.startsWith(".")).map((f) => `img/${f}`);
const precached = dist.stampServiceWorker(DIST, {
  id: "calcu59",   // 2.3.0's cache names: its caches go at the first activation
  core: ["vendor/react.production.min.js", "vendor/react-dom.production.min.js", "wasm/ti59-core.js", "wasm/ti59-core.wasm",
    ...fonts, ...images],
});
console.log(`app/sw.js: ${precached.length} precached files`);
const manifest = dist.writeManifest(DIST, { name: "Calc-U-59-web", version });
console.log(`MANIFEST.json: ${version}, ${manifest.commit}, ${Object.keys(manifest.files).length} files`);
